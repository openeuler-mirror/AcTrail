macro_rules! value_codebook {
    ($($code:literal => $value:literal),+ $(,)?) => {
        pub(super) fn value_code(value: &str) -> Option<u8> {
            match value {
                $($value => Some($code),)+
                _ => None,
            }
        }

        pub(super) fn value_for_code(code: u8) -> Option<&'static str> {
            match code {
                $($code => Some($value),)+
                _ => None,
            }
        }
    };
}

